"""MASM printer (`ml64`, Win64 only): the same machine IR as `nasm.py`, in Microsoft's syntax.

Differences from NASM that matter here:
- memory operands carry `byte ptr` … `ymmword ptr`, and a bare symbol in brackets is already
  RIP-relative (no `default rel`);
- functions are `name PROC PUBLIC` … `name ENDP`; labels inside a PROC are local to it
  (`L_<name>` for the MIR's `.<name>`);
- exports are `-export:` directives written into a `.drectve` segment, as in NASM: `PROC EXPORT`
  writes `/EXPORT:`, which MSVC's link.exe reads but GNU ld (MinGW) ignores;
- sections are segments: `_TEXT`, `_DATA`, and the constants in `_NVOLK`, aliased to `.rdata`
  with 64-byte alignment (the simplified `.const` segment is only 16-byte aligned);
- `OPTION CASEMAP:NONE`: symbol names are case-sensitive, like the C side."""
from __future__ import annotations

from . import encode
from .mir import Imm, Lab, Mem, Reg
from .nasm import reg

_SIZE = {8: "byte", 16: "word", 32: "dword", 64: "qword", 128: "xmmword", 256: "ymmword"}
_OPS = {"trunc32": "mov", "callind": "call", "tailjmp": "jmp", "tailcall": "jmp"}


def _lab(name: str) -> str:
    return "L_" + name[1:] if name.startswith(".") else name


def _imm(v: int) -> str:
    return str(v - (1 << 64) if v >= (1 << 63) else v)


def operand(a) -> str:
    if isinstance(a, Reg):
        return reg(a.r, a.w)
    if isinstance(a, Imm):
        return _imm(a.v)
    if isinstance(a, Lab):
        return _lab(a.name)
    if isinstance(a, Mem):
        size = f"{_SIZE[a.w]} ptr " if a.w else ""
        if a.sym is not None:
            d = f" + {a.disp}" if a.disp else ""
            return f"{size}[{a.sym}{d}]"
        parts = []
        if a.base is not None:
            parts.append(reg(a.base, 64))
        if a.index is not None:
            parts.append(reg(a.index, 64) + (f"*{a.scale}" if a.scale != 1 else ""))
        s = " + ".join(parts)
        if a.disp:
            s += f" - {-a.disp}" if a.disp < 0 else f" + {a.disp}"
        return f"{size}[{s}]"
    raise TypeError(a)


def _sized(a, args):
    """ml64 wants the size of a memory operand that NASM infers from the register beside it."""
    if isinstance(a, Mem) and not a.w:
        for o in args:
            if isinstance(o, Reg) and o.r.cls == "v":
                return Mem(a.base, a.index, a.scale, a.disp, a.sym, o.w, a.arg, a.spill)
    return a


def function(name: str, code: list, public: bool, export_all: bool = False) -> list:
    # PROC FRAME: ml64 writes the Win64 unwind info from the prologue directives
    out = [f"{name} PROC PUBLIC FRAME" if encode.unwind(code) else f"{name} PROC PUBLIC"]
    for ins in code:
        if ins.op == "label":
            out.append(f"{_lab(ins.args[0].name)}:")
            continue
        if ins.op == "endprolog":
            out.append("    .ENDPROLOG")
            continue
        if ins.op == "align":
            out += [f"    DB {', '.join(str(b) for b in nop)}" for nop in encode.nops(ins.args[2].v)]
            continue
        op = _OPS.get(ins.op, ins.op)
        raw = encode.vex_store_form(ins)
        if raw:              # the 2-byte-VEX store form, which ml64 does not pick by itself
            out.append(f"    DB {', '.join(str(b) for b in raw)}    ; {op} "
                       + ", ".join(operand(a) for a in ins.args))
            continue
        args = ", ".join(operand(_sized(a, ins.args)) for a in ins.args)
        if ins.hint == "short":     # the size encode.relax decided; ml64 would pick its own
            args = f"SHORT {args}"
        elif ins.hint == "near":
            args = f"NEAR PTR {args}"
        out.append(f"    {op} {args}".rstrip())
        if ins.hint == "push":
            out.append(f"    .PUSHREG {operand(ins.args[0])}")
        elif ins.hint == "alloc":
            out.append(f"    .ALLOCSTACK {ins.args[1].v}")
        elif ins.hint == "savexmm":
            out.append(f"    .SAVEXMM128 {reg(ins.args[1].r, 128)}, {ins.args[0].disp}")
    out.append(f"{name} ENDP")
    return out


def module(functions: list, fmt: str, consts: dict = None, tables: dict = None,
           fn_tables: dict = None, ptrs: dict = None, export_all: bool = False) -> str:
    """Same arguments as `nasm.module`; fmt must be "win64"."""
    assert fmt == "win64", "MASM (ml64) targets Win64 only"
    ptrs = ptrs or {}
    defined = {n for n, _, _ in functions} | set(ptrs)
    lines = ["; Generated by NVOL (Native Vector Operations Library). Do not edit.",
             "; SPDX-License-Identifier: MIT OR Apache-2.0",
             "OPTION CASEMAP:NONE"]
    externs = sorted({a.name for _, code, _ in functions for ins in code if ins.op != "label"
                      for a in ins.args if isinstance(a, Lab) and not a.name.startswith(".")
                      and a.name not in defined})
    lines += [f"EXTERN {n}:PROC" for n in externs]
    exports = [n for n, _, public in functions if public or export_all]
    if exports:
        lines.append('_DRECTVE SEGMENT INFO ALIAS(".drectve")')
        lines += [f'    DB "-export:{n} "' for n in exports]
        lines.append("_DRECTVE ENDS")
    if consts or tables:
        lines.append("_NVOLK SEGMENT ALIGN(64) READ ALIAS(\".rdata\") 'CONST'")
        for data, lab in (consts or {}).items():
            lines.append("ALIGN 32")         # (rows of 16: ml64 limits the length of a line)
            rows = [", ".join(str(b) for b in data[i:i + 16]) for i in range(0, len(data), 16)]
            lines.append(f"{lab} DB {rows[0]}")
            lines += [f"    DB {r}" for r in rows[1:]]
        for name, data in (tables or {}).items():
            lines.append("ALIGN 64")
            rows = [", ".join(str(b) for b in data[i:i + 16]) for i in range(0, len(data), 16)]
            lines.append(f"nvol_tbl_{name} DB {rows[0]}")
            lines += [f"    DB {r}" for r in rows[1:]]
        lines.append("_NVOLK ENDS")
    if ptrs:
        lines.append("_DATA SEGMENT")
        for p, target in ptrs.items():
            lines += ["ALIGN 8", f"PUBLIC {p}", f"{p} DQ {target}"]
        lines.append("_DATA ENDS")
    lines.append("_TEXT SEGMENT")             # (16-aligned: PARA)
    off = 0
    for name, code, public in functions:
        lines.append("")
        pad = (-off) % 16
        lines += [f"    DB {', '.join(str(b) for b in nop)}" for nop in encode.nops(pad)]
        lines += function(name, code, public, export_all)
        off += pad + encode.code_size(code)
    for name, fns in (fn_tables or {}).items():
        lines += ["", "ALIGN 8", f"nvol_fntbl_{name} DD {fns[0]} - nvol_fntbl_{name}"]
        lines += [f"    DD {fn} - nvol_fntbl_{name}" for fn in fns[1:]]
    lines += ["_TEXT ENDS", "END"]
    return "\n".join(lines) + "\n"


def find_ml64():
    """Path of ml64.exe: $ML64, ml64 on PATH, or the newest MSVC toolset vswhere knows; None if
    there is none (not Windows, no Visual Studio C++ tools)."""
    import os
    import re
    import shutil
    import subprocess
    if os.environ.get("ML64"):
        return os.environ["ML64"]
    if shutil.which("ml64"):
        return shutil.which("ml64")
    vswhere = os.path.join(os.environ.get("ProgramFiles(x86)", r"C:\Program Files (x86)"),
                           "Microsoft Visual Studio", "Installer", "vswhere.exe")
    if not os.path.exists(vswhere):
        return None
    out = subprocess.run([vswhere, "-latest", "-products", "*", "-find",
                          r"VC\Tools\MSVC\**\bin\Hostx64\x64\ml64.exe"],
                         capture_output=True, text=True).stdout.split("\n")
    found = [p.strip() for p in out if p.strip()]

    def version(p):
        m = re.search(r"MSVC[\\/](\d+)\.(\d+)\.(\d+)", p)
        return tuple(int(x) for x in m.groups()) if m else ()
    return max(found, key=version) if found else None
