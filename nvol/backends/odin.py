V = {16: "V16", 32: "V32"}


def _seq(xs):
    return ", ".join(str(x) for x in xs)


def _shin(n, k):            # simd_shuffle(b, a, ...): full-width shift-in of k bytes
    return _seq(n - k + i for i in range(n))


def _hshin(n, k):           # per 128-bit lane shift-in
    out = []
    for lane in range(n // 16):
        for i in range(16):
            out.append(16 * lane + 16 - k + i if i < k else n + 16 * lane + i - k)
    return _seq(out)


def _unpack(n, hi):
    out = []
    for lane in range(n // 16):
        for i in (range(8, 16) if hi else range(8)):
            out += [16 * lane + i, n + 16 * lane + i]
    return _seq(out)


