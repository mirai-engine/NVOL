"""Python backend: a ctypes binding over the generated C library.

Output: `nvol_ops.py`. It loads `nvol.dll` / `libnvol.so` / `libnvol.dylib`
(built from the C backend output) from its own directory or `$NVOL_LIB`.
Accepts any contiguous bytes-like object without copying (bytes, bytearray,
memoryview, mmap, numpy arrays).
"""
from __future__ import annotations

from .. import ir
from . import finder, iters, packed

TEMPLATE = '''"""Generated by NVOL (Native Vector Operations Library). Do not edit.
SPDX-License-Identifier: MIT OR Apache-2.0

ctypes binding to the NVOL C library. Build it with e.g.:
    gcc -O2 -shared -DNVOL_BUILD_DLL -o nvol.dll nvol.c        (Windows)
    cc  -O2 -shared -fPIC -o libnvol.so nvol.c                 (Linux)
"""
import ctypes
import os
import sys
from typing import Optional

_NONE = (1 << (8 * ctypes.sizeof(ctypes.c_size_t))) - 1


def _load():
    here = os.path.dirname(os.path.abspath(__file__))
    names = {{"win32": ["nvol.dll"], "darwin": ["libnvol.dylib"]}}.get(sys.platform, ["libnvol.so"])
    cands = [os.environ["NVOL_LIB"]] if os.environ.get("NVOL_LIB") else [os.path.join(here, n) for n in names]
    for c in cands:
        if os.path.exists(c):
            return ctypes.CDLL(c)
    raise OSError("NVOL native library not found; tried: " + ", ".join(cands))


_lib = _load()


def _buf(hay):
    """(address, length, keepalive) for a contiguous bytes-like object.

    No copy for bytes and writable buffers; read-only non-bytes buffers are
    copied once. Keep the third value alive while the address is in use.
    """
    if not isinstance(hay, bytes):
        mv = memoryview(hay).cast("B")
        if not mv.readonly:
            if not len(mv):
                return 0, 0, mv
            c = ctypes.c_char.from_buffer(mv)
            return ctypes.addressof(c), len(mv), c
        hay = mv.tobytes()
    return ctypes.cast(ctypes.c_char_p(hay), ctypes.c_void_p).value or 0, len(hay), hay

{functions}
'''


def _byteset(module) -> list:
    """Byte-set search: the state sizes and offsets (as in every backend) and a ByteSet
    class over nvol_byteset_init / nvol_find_byteset_raw / nvol_find_not_byteset_raw."""
    if not any(f.name == "nvol_byteset_init" for f in module.functions):
        return []
    from ..kernels.byteset import CONSTANTS
    out = [f"BYTESET_{n} = {v}  # {doc}" for n, v, doc in CONSTANTS]
    out += [
        "_lib.nvol_byteset_init.argtypes = [ctypes.c_void_p, ctypes.c_size_t, ctypes.c_void_p]",
        "_lib.nvol_byteset_init.restype = None",
        "for _f in (_lib.nvol_find_byteset_raw, _lib.nvol_find_not_byteset_raw):",
        "    _f.argtypes = [ctypes.c_void_p, ctypes.c_void_p, ctypes.c_void_p]",
        "    _f.restype = ctypes.c_void_p",
        "",
        "",
        "class ByteSet:",
        '    """A set of bytes, built once; find() and find_not() search a bytes-like object."""',
        "",
        "    def __init__(self, members: bytes):",
        "        m = bytes(members)",
        "        self._cls = (ctypes.c_uint8 * BYTESET_CLASS_BYTES)()",
        "        _lib.nvol_byteset_init(m, len(m), self._cls)",
        "",
        "    def _run(self, f, hay, start):",
        "        p, ln, _keep = _buf(hay)",
        "        if start < 0 or start > ln:",
        "            raise IndexError(start)",
        "        r = f(self._cls, p + start, p + ln)",
        "        return None if not r else r - p",
        "",
        "    def find(self, hay, start: int = 0) -> Optional[int]:",
        '        """First position >= start whose byte is in the set, or None."""',
        "        return self._run(_lib.nvol_find_byteset_raw, hay, start)",
        "",
        "    def find_not(self, hay, start: int = 0) -> Optional[int]:",
        '        """First position >= start whose byte is not in the set, or None."""',
        "        return self._run(_lib.nvol_find_not_byteset_raw, hay, start)",
        "",
    ]
    return out


def generate(module) -> dict:
    module = ir.for_languages(module)
    if isinstance(module, dict):                 # the binding only needs the (shared) API
        module = next(iter(module.values()))
    out = []
    for kind, name, n in module.api:
        if kind in ("memmem", "teddy"):
            continue
        short = name.removeprefix("nvol_")
        argtypes = ["ctypes.c_uint8"] * n + ["ctypes.c_void_p", "ctypes.c_size_t"]
        out.append(f"_lib.{name}.argtypes = [{', '.join(argtypes)}]")
        out.append(f"_lib.{name}.restype = ctypes.c_size_t")
        params = "".join(f"n{i + 1}: int, " for i in range(n))
        nargs = "".join(f"n{i + 1}, " for i in range(n))
        doc = next(f.doc for f in module.functions if f.name == name)
        if kind == "count":
            out.append(f"\n\ndef {short}({params}hay) -> int:")
            out.append(f'    """{doc}"""')
            out.append("    p, ln, _keep = _buf(hay)")
            out.append(f"    return _lib.{name}({nargs}p, ln)")
        else:
            out.append(f"\n\ndef {short}({params}hay) -> Optional[int]:")
            out.append(f'    """{doc}"""')
            out.append("    p, ln, _keep = _buf(hay)")
            out.append(f"    r = _lib.{name}({nargs}p, ln)")
            out.append("    return None if r == _NONE else r")
        out.append("\n")
    out += iters.python(module) + finder.python(module) + packed.python(module) + _byteset(module)
    if any(f.name == "nvol_json_index_raw" for f in module.functions):
        from ..kernels.json import CONSTANTS as JSON_CONSTANTS
        out += [f"JSON_{n} = {v}  # {doc}" for n, v, doc in JSON_CONSTANTS]
    return {"nvol_ops.py": TEMPLATE.format(functions="\n".join(out).rstrip() + "\n")}
