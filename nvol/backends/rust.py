"""Rust backend (edition 2021+): x86_64 (SSE2/SSSE3/AVX2, runtime dispatch via std)
and aarch64 (NEON), each in a `#[cfg(target_arch)]` `raw` module.

Output: a single module file `nvol.rs` with
  * `pub mod raw`  -- the generated `unsafe fn`s over (ptr, len),
  * safe wrappers  -- `memchr(n1, &[u8]) -> Option<usize>`, `count(..) -> usize`.
"""
from __future__ import annotations

from .. import ir
from . import finder, iters, packed
from ..isa import lowering
from .base import Printer

HEADER = """// Generated by NVOL (Native Vector Operations Library). Do not edit.
// SPDX-License-Identifier: MIT OR Apache-2.0
#![allow(unused_parens, unused_mut, unused_unsafe, non_snake_case, dead_code, while_true, unused_assignments)]
#![allow(clippy::all)]
"""


class RustPrinter(Printer):
    lang = "rust"

    def ty(self, t):
        if t is ir.VEC:
            return self.isa.vec_type["rust"]
        return {ir.U8: "u8", ir.U32: "u32", ir.U64: "u64", ir.USIZE: "usize",
                ir.BOOL: "bool", ir.PTR: "*const u8", ir.MPTR: "*mut u8", ir.VOID: "()",
                ir.VISIT: "&mut impl FnMut(*const u8, u64) -> bool"}[t]

    def visit(self, cb, at, mask):
        return f"({cb})({at}, {mask})"

    def e(self, x) -> str:
        # a visitor passed on to another kernel: reborrow, the caller keeps it
        if type(x) is ir.Var and x.ty is ir.VISIT:
            return f"&mut *{x.name}"
        return super().e(x)

    def const(self, c):
        if c.value is None:
            return "core::ptr::null()" if c.ty is ir.PTR else "usize::MAX"
        if c.ty is ir.BOOL:
            return "true" if c.value else "false"
        return f"{c.value}{self.ty(c.ty)}"

    def special_bin(self, op, a, b, ty):
        if op in ("max", "min"):
            return f"{a}.{op}({b})"
        return f"{a}.wrapping_{op[1:]}({b})"

    def call_table(self, table, idx, args):
        return f"(NVOL_FNTBL_{table.upper()}[{idx}])({', '.join(args)})"

    def table_load(self, table, idx):
        return f"(*NVOL_TBL_{table.upper()}.get_unchecked({idx}))"

    def ptr_add(self, p, n): return f"{p}.add({n})"
    def ptr_sub(self, p, n): return f"{p}.sub({n})"
    def ptr_diff(self, a, b): return f"(({a} as usize) - ({b} as usize))"
    def ptr_addr(self, p): return f"({p} as usize)"
    def load8(self, p): return f"(*{p})"
    def cast(self, x, t): return f"({x} as {self.ty(t)})"

    def block(self, stmts):
        for s in stmts:
            if isinstance(s, ir.Let):
                m = "mut " if s.mut else ""
                self.line(f"let {m}{s.var.name}: {self.ty(s.var.ty)} = {self.e(s.value)};")
            elif isinstance(s, ir.Assign):
                self.line(f"{s.var.name} = {self.e(s.value)};")
            elif isinstance(s, ir.While):
                self.line(f"while {self.e(s.cond)} {{")
                self.depth += 1; self.block(s.body); self.depth -= 1
                self.line("}")
            elif isinstance(s, ir.If):
                self.line(f"if {self.e(s.cond)} {{")
                self.depth += 1; self.block(s.then); self.depth -= 1
                if s.els:
                    self.line("} else {")
                    self.depth += 1; self.block(s.els); self.depth -= 1
                self.line("}")
            elif isinstance(s, ir.Return):
                self.line("return;" if s.value is None else f"return {self.e(s.value)};")
            elif isinstance(s, ir.Store8):
                self.line(f"*({self.e(s.ptr)}) = ({self.e(s.value)}) as u8;")
            elif isinstance(s, ir.Store64):
                self.line(f"({self.e(s.ptr)} as *mut u64).write_unaligned({self.e(s.value)});")
            elif isinstance(s, ir.StoreVec):
                self.line(lowering(self.isa, "rust", "store_u").format(self.e(s.ptr), self.e(s.value)) + ";")
            else:
                raise TypeError(s)

    def ifunc(self, f: ir.Function):
        """AtomicPtr cache resolved on first call, exactly like memchr's unsafe_ifunc!."""
        self.isa = None
        if len(f.ifunc) == 1 and f.ifunc[0][0] is None:      # nothing to choose: direct call
            params = ", ".join(f"{p.name}: {self.ty(p.ty)}" for p in f.params)
            args = ", ".join(f"&mut *{p.name}" if p.ty is ir.VISIT else p.name for p in f.params)
            if f.doc:
                self.line(f"/// {f.doc}")
            self.line("#[inline(always)]")
            self.line(f"pub unsafe fn {f.name}({params}) -> {self.ty(f.ret)} {{ unsafe {{ {f.ifunc[0][1]}({args}) }} }}")
            self.line()
            return
        params = ", ".join(f"{p.name}: {self.ty(p.ty)}" for p in f.params)
        if any(p.ty is ir.VISIT for p in f.params):
            # generic over the visitor: no function pointer to cache, so test the
            # features on each call (std caches the CPUID result itself)
            args = ", ".join(f"&mut *{p.name}" if p.ty is ir.VISIT else p.name for p in f.params)
            if f.doc:
                self.line(f"/// {f.doc}")
            self.line("#[inline(always)]")
            self.line(f"pub unsafe fn {f.name}({params}) -> {self.ty(f.ret)} {{")
            self.depth += 1
            default = [t for c, t in f.ifunc if c is None][0]
            for cond, target in f.ifunc:
                if cond is not None:
                    self.line(f"if {self.e(cond)} {{ return unsafe {{ {target}({args}) }}; }}")
            self.line(f"unsafe {{ {default}({args}) }}")
            self.depth -= 1
            self.line("}")
            self.line()
            return
        ptys = ", ".join(self.ty(p.ty) for p in f.params)
        args = ", ".join(p.name for p in f.params)
        ret = self.ty(f.ret)
        if f.doc:
            self.line(f"/// {f.doc}")
        self.line("#[inline(always)]")
        self.line(f"pub unsafe fn {f.name}({params}) -> {ret} {{")
        self.depth += 1
        self.line("use core::sync::atomic::{AtomicPtr, Ordering};")
        self.line(f"type F = unsafe fn({ptys}) -> {ret};")
        self.line("static FN: AtomicPtr<()> = AtomicPtr::new(resolve as F as *mut ());")
        self.line(f"unsafe fn resolve({params}) -> {ret} {{")
        self.depth += 1
        default = [t for c, t in f.ifunc if c is None][0]
        self.line(f"let mut f: F = {default};")
        for cond, target in reversed([(c, t) for c, t in f.ifunc if c is not None]):
            self.line(f"if {self.e(cond)} {{ f = {target}; }}")
        self.line("FN.store(f as *mut (), Ordering::Relaxed);")
        self.line(f"unsafe {{ f({args}) }}")
        self.depth -= 1
        self.line("}")
        self.line("let f = FN.load(Ordering::Relaxed);")
        self.line(f"unsafe {{ core::mem::transmute::<*mut (), F>(f)({args}) }}")
        self.depth -= 1
        self.line("}")
        self.line()

    def function(self, f: ir.Function):
        if f.ifunc:
            return self.ifunc(f)
        self.isa = self.isa_of(f)
        if f.doc:
            self.line(f"/// {f.doc}")
        if self.isa and self.isa.target["rust"] not in ("", "sse2"):
            self.line(f'#[target_feature(enable = "{self.isa.target["rust"]}")]')
            self.line("#[inline(never)]" if f.noinline else "#[inline]")
        else:
            self.line("#[inline(never)]" if f.noinline else "#[inline(always)]")
        params = ", ".join(f"{p.name}: {self.ty(p.ty)}" for p in f.params)
        vis = "pub " if f.public else "pub(crate) "
        self.line(f"{vis}unsafe fn {f.name}({params}) -> {self.ty(f.ret)} {{")
        self.depth += 1
        self.line("unsafe {")
        self.depth += 1
        self.block(f.body)
        self.depth -= 1
        self.line("}")
        self.depth -= 1
        self.line("}")
        self.line()

    def emit(self) -> dict:
        mods = self.mods
        primary = self.mod
        self.out = [HEADER]
        for arch, mod in mods.items():
            self.mod = mod
            self.out += [f"#[cfg(target_arch = \"{arch}\")]", "pub mod raw {",
                         f"    use core::arch::{arch}::*;", ""]
            if any(f.name == "nvol_byteset_init" for f in mod.functions):
                from ..kernels.byteset import CONSTANTS
                for n, v, doc in CONSTANTS:
                    self.out += [f"    /// {doc}", f"    pub const NVOL_BYTESET_{n}: usize = {v};"]
                self.out.append("")
            for name, data in self.mod.tables.items():
                self.out.append(f"    pub(crate) static NVOL_TBL_{name.upper()}: [u8; {len(data)}] = {list(data)};")
            self.out.append("")
            self.depth = 1
            for f in self.mod.functions:
                self.function(f)
            self._fn_tables()
            self.depth = 0
            self.out += ["}", ""]
        self.mod = primary
        self._wrappers()
        self.out += iters.rust(self.mod) + finder.rust(self.mod) + packed.rust(self.mod)
        return {"nvol.rs": self.text()}

    def _fn_tables(self):
        for name, fns in self.mod.fn_tables.items():
            f0 = self.mod.fn(fns[0])
            saved, self.isa = self.isa, None
            sig = f"unsafe fn({', '.join(self.ty(p.ty) for p in f0.params)}) -> {self.ty(f0.ret)}"
            self.isa = saved
            self.line(f"pub(crate) static NVOL_FNTBL_{name.upper()}: [{sig}; {len(fns)}] = [")
            for fn in fns:
                self.line(f"    {fn},")
            self.line("];")
            self.line()

    def _wrappers(self):
        for kind, name, n in self.mod.api:
            if kind in ("memmem", "teddy"):
                continue
            short = name.removeprefix("nvol_")
            needles = "".join(f"n{i + 1}: u8, " for i in range(n))
            nargs = "".join(f"n{i + 1}, " for i in range(n))
            if kind == "count":
                self.out.append("#[inline]")
                self.out.append(f"pub fn {short}({needles}hay: &[u8]) -> usize {{")
                self.out.append(f"    unsafe {{ raw::{name}({nargs}hay.as_ptr(), hay.len()) }}")
                self.out.append("}")
            else:
                self.out.append("#[inline]")
                self.out.append(f"pub fn {short}({needles}hay: &[u8]) -> Option<usize> {{")
                # Straight from the raw pointer to Option: going through the
                # index API (NULL -> usize::MAX -> None) left a branchless
                # sbb/or/cmov chain after every call (-8 % on 16-byte memchr).
                self.out.append("    let s = hay.as_ptr();")
                if name == "nvol_first_non_ascii":
                    # 16-31 bytes on x86_64: SSE2 (the baseline) inline, the first and the last
                    # 16 bytes, so the call skips the dispatch's indirect call and the AVX2
                    # entry's vzeroupper, which bstr's inlined static SSE2 does not pay
                    # (PENDING item 29)
                    self.out += [
                        "    #[cfg(target_arch = \"x86_64\")]",
                        "    if hay.len() >= 16 && hay.len() < 32 {",
                        "        use core::arch::x86_64::{__m128i, _mm_loadu_si128, _mm_movemask_epi8};",
                        "        let t = hay.len() - 16;",
                        "        let (a, b) = unsafe { (_mm_movemask_epi8(_mm_loadu_si128(s as *const __m128i)) as u32,",
                        "                               _mm_movemask_epi8(_mm_loadu_si128(s.add(t) as *const __m128i)) as u32) };",
                        "        return if a != 0 { Some(a.trailing_zeros() as usize) }",
                        "               else if b != 0 { Some(t + b.trailing_zeros() as usize) } else { None };",
                        "    }",
                    ]
                self.out.append(f"    let p = unsafe {{ raw::{name}_raw({nargs}s, s.add(hay.len())) }};")
                self.out.append("    if p.is_null() { None } else { Some(p as usize - s as usize) }")
                self.out.append("}")
            self.out.append("")


def generate(module) -> dict:
    """module: an ir.Module or {arch: ir.Module}."""
    module = ir.for_languages(module)
    mods = module if isinstance(module, dict) else {getattr(module, "arch", "x86_64"): module}
    p = RustPrinter(next(iter(mods.values())))
    p.mods = mods
    return p.emit()
